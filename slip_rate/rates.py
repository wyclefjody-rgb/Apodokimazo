"""
    Slip-rate study, step 3: slip rates and the probability of Paul's clean record (PREDICTIONS.md section 4).

    Reads codes.txt, checks that every candidate found by candidates.py is coded, and computes for each text the
    number of datable items, slips, slip rate and slips per 1,000 words. Then, for the pooled Group A rate r with
    r ~ Beta(slips + 1, non-slips + 1), the probability that a writer with those habits produces Paul's record:
    P = E[(1 - r)^N]  (no slip in N items).

    Output: RESULTS.md.

    Usage (from the kit folder):   python -X utf8 slip_rate/rates.py
"""
import math
import os
import re
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
import candidates

CODES = os.path.join(HERE, "codes.txt")
OUTPUT = os.path.join(HERE, "RESULTS.md")
CODE_VALUES = ["fits", "slip", "either", "not"]
GAP = {"Pastorals": "c. 40-80 years", "spurious Ignatius": "c. 250 years", "Clementine letters to James":
       "c. 150-250 years", "2 Peter": "c. 50-90 years", "Acts of John": "c. 60-110 years", "Acts of Thomas":
       "c. 170-200 years", "Acts of Barnabas": "c. 400 years", "core four": "-"}
CLOSEST = ["Pastorals", "2 Peter", "Acts of John"]
VANISHING_POINT_N = 14


def read_codes():
    items = []
    with open(CODES, encoding="utf8") as file:
        number = 0
        for line in file:
            number += 1
            if line.startswith("#") or not line.strip():
                continue
            cells = re.split(r"\s+\|\s+", line.rstrip("\n"), maxsplit=5)
            if len(cells) != 6:
                sys.exit(f"codes.txt line {number}: expected 6 columns")
            text, places, item, code, strength, reason = cells
            if code not in CODE_VALUES:
                sys.exit(f"codes.txt line {number}: unknown code '{code}'")
            place_list = []
            for place in places.split(";"):
                place_list.append(place.strip())
            items.append({"text": text, "places": place_list, "item": item, "code": code, "strength": strength,
                          "reason": reason})
    return items


def log_beta(a, b):
    return math.lgamma(a) + math.lgamma(b) - math.lgamma(a + b)


def p_clean(slips, items, n):
    """E[(1 - r)^n] for r ~ Beta(slips + 1, items - slips + 1)."""
    a = slips + 1
    b = items - slips + 1
    return math.exp(log_beta(a, b + n) - log_beta(a, b))


def p_at_most_one(slips, items, n):
    a = slips + 1
    b = items - slips + 1
    none = math.exp(log_beta(a, b + n) - log_beta(a, b))
    one = n * math.exp(log_beta(a + 1, b + n - 1) - log_beta(a, b))
    return none + one


def main():
    sys.stdout.reconfigure(encoding="utf-8")
    candidates.extract.norm = candidates.keep_accents
    topics = candidates.read_topics()
    items = read_codes()
    words = {}
    groups = {}
    missing = []
    for name, group, sources in candidates.TEXTS:
        groups[name] = group
        passages = candidates.load(sources)
        total = 0
        for place, shown, forms in passages:
            total += len(forms)
            if candidates.hits_in(forms, topics):
                covered = False
                for item in items:
                    if item["text"] == name and place in item["places"]:
                        covered = True
                if not covered:
                    missing.append(f"{name}: {place}")
        words[name] = total
    if missing:
        print("Candidates without a code:")
        print("\n".join(missing))
        sys.exit(f"{len(missing)} candidates not coded; nothing written.")

    stats = {}
    for name in words:
        counted = {"fits": 0, "slip": 0, "either": 0, "strong slip": 0, "weak slip": 0}
        for item in items:
            if item["text"] != name or item["code"] == "not":
                continue
            counted[item["code"]] += 1
            if item["code"] == "slip" and item["strength"] == "strong":
                counted["strong slip"] += 1
            if item["code"] == "slip" and item["strength"] == "weak":
                counted["weak slip"] += 1
        counted["items"] = counted["fits"] + counted["slip"] + counted["either"]
        stats[name] = counted

    lines = ["# How often do later writers slip? Results", "",
             "Rules: PREDICTIONS.md (SHA-256 21f88a62…0835) and AMENDMENTS.md. Generated by rates.py from "
             "codes.txt (every candidate of candidates.py coded).", "",
             "## Datable items and slips, text by text", "",
             "| text | group | gap between setting and writing | words | datable items | fits the setting | either | "
             "slips (strong / medium / weak) | slip rate | slips per 1,000 words |",
             "|---|---|---|---|---|---|---|---|---|---|"]
    for name in words:
        s = stats[name]
        medium = s["slip"] - s["strong slip"] - s["weak slip"]
        rate = s["slip"] / s["items"] if s["items"] else 0
        lines.append(f"| {name} | {groups[name]} | {GAP[name]} | {words[name]:,} | {s['items']} | {s['fits']} | "
                     f"{s['either']} | {s['slip']} ({s['strong slip']} / {medium} / {s['weak slip']}) | "
                     f"{100 * rate:.0f}% | {1000 * s['slip'] / words[name]:.2f} |")
    lines.append("")

    paul_items = stats["core four"]["items"]
    paul_slips = stats["core four"]["slip"]
    pools = [("Group A (primary)", ["Pastorals", "spurious Ignatius", "Clementine letters to James"], False),
             ("Group A, weak slips not counted", ["Pastorals", "spurious Ignatius", "Clementine letters to James"],
              True),
             ("Groups A and B", ["Pastorals", "spurious Ignatius", "Clementine letters to James", "2 Peter",
                                 "Acts of John", "Acts of Thomas", "Acts of Barnabas"], False),
             ("Closest in time (under 150 years)", CLOSEST, False)]
    lines.append("## How likely is Paul's record from a later writer?")
    lines.append("")
    lines.append(f"Paul's core four: **{paul_items} datable items, {paul_slips} slips**. P is the probability that a "
                 "writer with the pool's slip habits would slip nowhere in that many items (Beta-binomial, "
                 "PREDICTIONS.md section 4).")
    lines.append("")
    lines.append("| pool | items | slips | pooled rate | P (no slip in Paul's items) | P (no slip in the 14 items of "
                 "vanishing_point) | P (at most one slip in Paul's items + 1 Thess 2:16) | Poisson check: P (no slip "
                 "in 20,566 words) |")
    lines.append("|---|---|---|---|---|---|---|---|")
    for label, members, drop_weak in pools:
        pooled_items = 0
        pooled_slips = 0
        pooled_words = 0
        for name in members:
            pooled_items += stats[name]["items"]
            slips = stats[name]["slip"]
            if drop_weak:
                slips -= stats[name]["weak slip"]
                pooled_items -= stats[name]["weak slip"]
            pooled_slips += slips
            pooled_words += words[name]
        rate = pooled_slips / pooled_items
        clean = p_clean(pooled_slips, pooled_items, paul_items)
        clean_old = p_clean(pooled_slips, pooled_items, VANISHING_POINT_N)
        one = p_at_most_one(pooled_slips, pooled_items, paul_items + 1)
        poisson = math.exp(-pooled_slips / pooled_words * words["core four"])
        lines.append(f"| {label} | {pooled_items} | {pooled_slips} | {100 * rate:.0f}% | {clean:.4f} | "
                     f"{clean_old:.4f} | {one:.4f} | {poisson:.1e} |")
    lines.append("")
    lines.append("The Poisson column treats slips as spread evenly through a text's words (AMENDMENTS.md 1): a "
                 "cross-check, not the primary measure.")
    lines.append("")
    lines.append("### Exploratory (added after the first run): writers differ")
    lines.append("")
    lines.append("Pooling treats all later writers as sharing one slip rate. They do not: the rates run from 0% "
                 "(Acts of Thomas) to 39%. Here each control text keeps its own rate, and P is the chance that a writer "
                 "drawn at random from the controls would be clean in Paul's items (the average of the texts' own "
                 "P values).")
    lines.append("")
    lines.append("| controls | P for each text | average P |")
    lines.append("|---|---|---|")
    for label, members in [("Group A", ["Pastorals", "spurious Ignatius", "Clementine letters to James"]),
                           ("Groups A and B", ["Pastorals", "spurious Ignatius", "Clementine letters to James",
                                               "2 Peter", "Acts of John", "Acts of Thomas", "Acts of Barnabas"]),
                           ("Closest in time", CLOSEST)]:
        values = []
        shown = []
        for name in members:
            value = p_clean(stats[name]["slip"], stats[name]["items"], paul_items)
            values.append(value)
            shown.append(f"{name} {value:.3f}")
        lines.append(f"| {label} | {'; '.join(shown)} | {sum(values) / len(values):.3f} |")
    lines.append("")

    lines.append("## Every datable item")
    lines.append("")
    lines.append("| text | item | code | strength | where | reason |")
    lines.append("|---|---|---|---|---|---|")
    for item in items:
        if item["code"] == "not":
            continue
        lines.append(f"| {item['text']} | {item['item']} | {item['code']} | {item['strength']} | "
                     f"{'; '.join(item['places'])} | {item['reason']} |")
    lines.append("")
    with open(OUTPUT, "w", encoding="utf8") as file:
        file.write("\n".join(lines) + "\n")
    print("\n".join(lines[:30]))
    print(f"\nWrote {OUTPUT}")


if __name__ == "__main__":
    main()
