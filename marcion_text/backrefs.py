"""
    Part A of marcion_text/PREDICTIONS.md: back-references in the ten letters of Marcion's edition.

    Finds every verse where a letter refers back to something said, written, taught or handed on before, using MorphGNT
    lemmas and parsing codes:
      προλέγω, προγράφω                      all forms
      γράφω                                  all forms except the perfect passive ("it is written": scripture)
      ἐπιστολή                               all forms
      παραγγέλλω, παραδίδωμι, διδάσκω,
      κηρύσσω, μανθάνω                       past tenses only (aorist, imperfect, perfect, pluperfect)
      μνημονεύω, ἀναμιμνῄσκω                 all forms
    Then reads the hand codes in backrefs_codes.txt (verse | type | target | reason) and tests, for every reference to
    another letter of the collection, whether that letter comes earlier in each candidate order.

    Output: BACKREFS.md.

    Usage (from the kit folder):   python -X utf8 marcion_text/backrefs.py
"""
import os
import re
import sys
from glob import glob

HERE = os.path.dirname(os.path.abspath(__file__))
KIT = os.path.join(HERE, "..")
SBLGNT = os.path.join(KIT, "sblgnt")
CODES = os.path.join(HERE, "backrefs_codes.txt")
OUTPUT = os.path.join(HERE, "BACKREFS.md")

LETTERS = ["Ro", "1Co", "2Co", "Ga", "Eph", "Php", "Col", "1Th", "2Th", "Phm"]
ALL_FORMS = {"προλέγω", "προγράφω", "ἐπιστολή", "μνημονεύω", "ἀναμιμνῄσκω"}
PAST_ONLY = {"παραγγέλλω", "παραδίδωμι", "διδάσκω", "κηρύσσω", "μανθάνω"}
PAST_TENSES = {"A", "I", "X", "Y"}
ORDERS = {
    "Marcion (Tertullian, Against Marcion 5)": ["Ga", "1Co", "2Co", "Ro", "1Th", "2Th", "Eph", "Col", "Php", "Phm"],
    "by length (later canonical)": ["Ro", "1Co", "2Co", "Ga", "Eph", "Php", "Col", "1Th", "2Th", "Phm"],
    "P46 (c. 200)": ["Ro", "1Co", "2Co", "Eph", "Ga", "Php", "Col", "1Th"],
}
TYPES = {"i": "oral teaching or warning during a visit", "ii": "an earlier passage of the same letter",
         "iii": "an earlier letter to the same addressees", "iv": "another letter of the collection",
         "v": "unclear", "x": "not a back-reference"}


def verses_of(book):
    paths = glob(os.path.join(SBLGNT, f"*-{book}-morphgnt.txt"))
    if not paths:
        sys.exit(f"No MorphGNT file for {book} in '{SBLGNT}'. Run setup_data.py first.")
    verses = []
    with open(paths[0], encoding="utf8") as file:
        for line in file:
            columns = line.split()
            place = f"{book} {int(columns[0][2:4])}:{int(columns[0][4:6])}"
            if not verses or verses[-1][0] != place:
                verses.append([place, [], []])
            verses[-1][1].append(columns[3])
            verses[-1][2].append((columns[6], columns[2]))
    return verses


def is_hit(lemma, parsing):
    if lemma in ALL_FORMS:
        return True
    if lemma == "γράφω":
        return not (parsing[1] == "X" and parsing[2] == "P")
    if lemma in PAST_ONLY:
        return parsing[1] in PAST_TENSES
    return False


def read_codes():
    codes = {}
    if not os.path.exists(CODES):
        return codes
    with open(CODES, encoding="utf8") as file:
        for line in file:
            if line.startswith("#") or not line.strip():
                continue
            place, kind, target, reason = re.split(r"\s+\|\s+", line.rstrip("\n"), maxsplit=3)
            if kind not in TYPES:
                sys.exit(f"Unknown type '{kind}' for {place}")
            codes[place] = (kind, target, reason)
    return codes


def main():
    sys.stdout.reconfigure(encoding="utf-8")
    codes = read_codes()
    hits = []
    for book in LETTERS:
        for place, words, tagged in verses_of(book):
            found = []
            for lemma, parsing in tagged:
                if is_hit(lemma, parsing) and lemma not in found:
                    found.append(lemma)
            if found:
                hits.append((place, found, " ".join(words)))
    uncoded = []
    counts = {}
    for kind in TYPES:
        counts[kind] = 0
    rows = []
    cross = []
    for place, found, text in hits:
        if place not in codes:
            uncoded.append(place)
            rows.append(f"| {place} | {', '.join(found)} | not yet coded | | | {text} |")
            continue
        kind, target, reason = codes[place]
        counts[kind] += 1
        rows.append(f"| {place} | {', '.join(found)} | {kind}: {TYPES[kind]} | {target} | {reason} | {text} |")
        if kind == "iv":
            cross.append((place, target))
    lines = ["# Back-references in the ten letters of Marcion's edition (Part A)", "",
             "Rules: PREDICTIONS.md section 2 (SHA-256 3c8dfa4b…c3c7). Generated by backrefs.py; codes in "
             "backrefs_codes.txt.", "", "| type | verses |", "|---|---|"]
    for kind, label in TYPES.items():
        lines.append(f"| {kind}: {label} | {counts[kind]} |")
    if uncoded:
        lines.append(f"| not yet coded | {len(uncoded)} |")
    lines.append("")
    lines.append("## References to another letter of the collection, tested against each order")
    lines.append("")
    if not cross:
        lines.append("None was coded as type iv.")
    else:
        header = "| verse | points to |"
        rule = "|---|---|"
        for name in ORDERS:
            header += f" earlier in {name}? |"
            rule += "---|"
        lines.append(header)
        lines.append(rule)
        for place, target in cross:
            book = place.split(" ")[0]
            row = f"| {place} | {target} |"
            for name, order in ORDERS.items():
                aim = re.split(r"[ ,;]", target)[0]
                if book in order and aim in order:
                    row += f" {'yes' if order.index(aim) < order.index(book) else 'no'} |"
                else:
                    row += " not in this order |"
            lines.append(row)
    lines.append("")
    lines.append("## Every hit")
    lines.append("")
    lines.append("| verse | terms | type | points to | reason | text |")
    lines.append("|---|---|---|---|---|---|")
    lines.extend(rows)
    with open(OUTPUT, "w", encoding="utf8") as file:
        file.write("\n".join(lines) + "\n")
    print("\n".join(lines[:16]))
    print(f"\nWrote {OUTPUT}")


if __name__ == "__main__":
    main()
